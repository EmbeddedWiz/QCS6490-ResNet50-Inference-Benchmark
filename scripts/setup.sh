#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

LOCAL_CONFIG="$PROJECT_ROOT/config/local.conf"
STRESSOR_DIR="$PROJECT_ROOT/stressor"

echo "=== QCS6490 ResNet-50 benchmark setup ==="
echo

echo "[1/5] Searching for QNN artifacts..."

QNN_ARTIFACT_DIR=""

if [[ -f "$PROJECT_ROOT/config/experiment.conf" ]]; then
    # shellcheck disable=SC1091
    source "$PROJECT_ROOT/config/experiment.conf"
    QNN_ARTIFACT_DIR="${QNN_ARTIFACT_DIR:-}"
fi

if [[ -n "$QNN_ARTIFACT_DIR" && -f "$QNN_ARTIFACT_DIR/qnn-net-run" ]]; then
    echo "Using configured QNN artifact directory:"
    echo "  $QNN_ARTIFACT_DIR"
else
    QNN_ARTIFACT_DIR="$(find "$HOME/Projects" -type f -name qnn-net-run -print -quit 2>/dev/null | xargs -r dirname || true)"
fi

if [[ -z "$QNN_ARTIFACT_DIR" ]]; then
    echo "ERROR: qnn-net-run was not found under $HOME/Projects"
    exit 1
fi

echo "QNN artifact directory:"
echo "  $QNN_ARTIFACT_DIR"
echo

echo "[2/5] Checking QNN runtime files..."

required_files=(
    "qnn-net-run"
    "libQnnHtp.so"
    "libQnnHtpV68Skel.so"
    "libQnnHtpV68Stub.so"
    "resnet50_aimet_quantized_6490.bin"
    "test_list.txt"
)

for file in "${required_files[@]}"; do
    if [[ ! -f "$QNN_ARTIFACT_DIR/$file" ]]; then
        echo "ERROR: missing QNN artifact:"
        echo "  $QNN_ARTIFACT_DIR/$file"
        exit 1
    fi
    echo "  OK  $file"
done

echo

echo "[3/5] Checking qnn-profile-viewer..."

QNN_PROFILE_VIEWER="$HOME/qnn-tools/2.37.1.250807/bin/qnn-profile-viewer"

if [[ ! -x "$QNN_PROFILE_VIEWER" ]]; then
    echo "ERROR: qnn-profile-viewer not found:"
    echo "  $QNN_PROFILE_VIEWER"
    exit 1
fi

echo "  OK  $QNN_PROFILE_VIEWER"
echo

echo "[4/5] Building CPU contention stressor..."

make -C "$STRESSOR_DIR"

echo

echo "[5/5] Writing local configuration..."

cat > "$LOCAL_CONFIG" <<EOF2
# Machine-specific configuration generated by setup.sh.

QNN_ARTIFACT_DIR="$QNN_ARTIFACT_DIR"
QNN_PROFILE_VIEWER="$QNN_PROFILE_VIEWER"

QNN_BACKEND="libQnnHtp.so"
QNN_CONTEXT="resnet50_aimet_quantized_6490.bin"
QNN_INPUT_LIST="test_list.txt"

CPU_LIST="4,5"
INFERENCES=1000
EOF2

chmod +x "$PROJECT_ROOT/scripts/run_benchmark.sh"
chmod +x "$PROJECT_ROOT/scripts/serve_report.sh"
chmod +x "$PROJECT_ROOT/scripts/analyze_results.py"
chmod +x "$PROJECT_ROOT/tools/termo2"

echo
echo "========================================"
echo "Setup complete."
echo "========================================"
echo
echo "QNN artifacts:"
echo "  $QNN_ARTIFACT_DIR"
echo
echo "Profile viewer:"
echo "  $QNN_PROFILE_VIEWER"
echo
echo "CPU contention:"
echo "  CPUs $CPU_LIST"
echo
echo "Next command:"
echo "  ./scripts/run_benchmark.sh"
